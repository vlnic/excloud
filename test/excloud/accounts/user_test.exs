defmodule Excloud.Accounts.UserTest do
  @moduledoc false

  use Excloud.DataCase, async: true

  alias Excloud.Accounts.Account
  alias Excloud.Accounts.User
  alias Excloud.Types.EncryptedString

  # A precomputed bcrypt hash; password hashing is outside the schema's scope.
  @hashed_password "$2b$12$LQv3c1yqBWVHxkd0LHAkCOYz6TtxIjTQJ05EkWvWsRDv1VEQ5C1eO"

  setup do
    account = %Account{} |> Account.changeset(%{type: :member}) |> Repo.insert!()
    %{account: account}
  end

  test "persists credentials with an internal id and an autogenerated UUIDv7", %{account: account} do
    before_insert = System.system_time(:millisecond)

    assert {:ok, user} =
      %User{account_id: account.id, hashed_password: @hashed_password}
      |> User.changeset(%{login: "alice"})
      |> Repo.insert()

    assert is_integer(user.id)
    assert user.id > 0
    assert Ecto.UUID.version(user.external_id) == 7
    assert Ecto.UUID.to_unix(user.external_id, :millisecond) >= before_insert
    assert Ecto.UUID.to_unix(user.external_id, :millisecond) <= System.system_time(:millisecond)

    reloaded = Repo.get!(User, user.id)
    assert reloaded.login == "alice"
    assert reloaded.hashed_password == @hashed_password
    assert reloaded.external_id == user.external_id
    assert %DateTime{} = reloaded.inserted_at
    assert %DateTime{} = reloaded.updated_at
    refute Map.has_key?(reloaded, :password)
    refute inspect(reloaded) =~ @hashed_password
  end

  test "requires a login and a prepared password hash" do
    changeset = User.changeset(%User{}, %{})

    assert errors_on(changeset) == %{
      login: ["can't be blank"],
      hashed_password: ["can't be blank"],
      account_id: ["can't be blank"]
    }
  end

  test "trims logins and rejects whitespace within them", %{account: account} do
    changeset =
      User.changeset(%User{account_id: account.id, hashed_password: @hashed_password}, %{
        login: " alice "
      })

    assert changeset.valid?
    assert get_change(changeset, :login) == "alice"

    for login <- ["alice smith", "alice\nsmith", "alice\tsmith"] do
      changeset =
        User.changeset(%User{account_id: account.id, hashed_password: @hashed_password}, %{
          login: login
        })

      assert "must not contain whitespace" in errors_on(changeset).login
    end
  end

  test "rejects blank and oversized logins", %{account: account} do
    for login <- ["", "   ", String.duplicate("a", 256)] do
      changeset =
        User.changeset(%User{account_id: account.id, hashed_password: @hashed_password}, %{
          login: login
        })

      assert %{login: [_ | _]} = errors_on(changeset)
    end
  end

  test "does not accept identifiers or credentials from attributes", %{account: account} do
    external_id = Ecto.UUID.generate(version: 7)

    changeset =
      User.changeset(%User{account_id: account.id, hashed_password: @hashed_password}, %{
        login: "alice",
        id: 123,
        account_id: -1,
        external_id: external_id,
        password: "plaintext",
        verification_key: "untrusted verification key",
        hashed_password: "untrusted hash"
      })

    assert changeset.valid?
    assert changeset.changes == %{login: "alice"}
    assert get_field(changeset, :account_id) == account.id
    assert get_field(changeset, :verification_key) == nil
    assert get_field(changeset, :hashed_password) == @hashed_password
    refute inspect(changeset) =~ @hashed_password
    refute inspect(changeset) =~ "plaintext"
  end

  test "enforces unique logins", %{account: account} do
    insert_user!(account, "alice")

    assert {:error, changeset} =
      %User{account_id: account.id, hashed_password: @hashed_password}
      |> User.changeset(%{login: "alice"})
      |> Repo.insert()

    assert "has already been taken" in errors_on(changeset).login
  end

  test "generates different UUIDs for different users", %{account: account} do
    first = insert_user!(account, "alice")
    second = insert_user!(account, "bob")

    refute first.id == second.id
    refute first.external_id == second.external_id
    assert Ecto.UUID.version(second.external_id) == 7
  end

  test "enforces unique external identifiers", %{account: account} do
    user = insert_user!(account, "alice")

    assert {:error, changeset} =
      %User{
        account_id: account.id,
        external_id: user.external_id,
        hashed_password: @hashed_password
      }
      |> User.changeset(%{login: "bob"})
      |> Repo.insert()

    assert "has already been taken" in errors_on(changeset).external_id
  end

  test "rejects non-v7 UUIDs at the database level", %{account: account} do
    assert {:error, changeset} =
      %User{
        account_id: account.id,
        external_id: Ecto.UUID.generate(),
        hashed_password: @hashed_password
      }
      |> User.changeset(%{login: "alice"})
      |> Repo.insert()

    assert "is invalid" in errors_on(changeset).external_id
  end

  test "rejects invalid UUID variants at the database level", %{account: account} do
    uuid = Ecto.UUID.generate(version: 7)
    invalid_variant = String.slice(uuid, 0, 19) <> "0" <> String.slice(uuid, 20, 16)

    assert {:error, changeset} =
      %User{
        account_id: account.id,
        external_id: invalid_variant,
        hashed_password: @hashed_password
      }
      |> User.changeset(%{login: "alice"})
      |> Repo.insert()

    assert "is invalid" in errors_on(changeset).external_id
  end

  test "keeps both identifiers when updating a login", %{account: account} do
    user = insert_user!(account, "alice")

    assert {:ok, updated} =
      user
      |> User.changeset(%{login: "alice_updated"})
      |> Repo.update()

    assert updated.id == user.id
    assert updated.external_id == user.external_id
    assert updated.account_id == user.account_id
    assert updated.hashed_password == user.hashed_password
  end

  test "requires an account even when credentials are present" do
    changeset = User.changeset(%User{hashed_password: @hashed_password}, %{login: "alice"})
    assert errors_on(changeset) == %{account_id: ["can't be blank"]}
  end

  test "multiple users reference the same shared account", %{account: account} do
    alice = insert_user!(account, "alice")
    bob = insert_user!(account, "bob")

    assert Repo.preload(alice, :account).account.id == account.id
    assert Repo.preload(bob, :account).account.id == account.id

    user_ids = account |> Repo.preload(:users) |> Map.fetch!(:users) |> Enum.map(& &1.id)
    assert Enum.sort(user_ids) == Enum.sort([alice.id, bob.id])
  end

  test "rejects a reference to a missing account", %{account: account} do
    Repo.delete!(account)

    assert {:error, changeset} =
      %User{account_id: account.id, hashed_password: @hashed_password}
      |> User.changeset(%{login: "alice"})
      |> Repo.insert()

    assert "does not exist" in errors_on(changeset).account_id
  end

  test "reassigns an account only through a trusted changeset", %{account: account} do
    user = insert_user!(account, "alice")
    another_account = %Account{} |> Account.changeset(%{type: :other}) |> Repo.insert!()

    assert {:ok, unchanged} =
      user
      |> User.changeset(%{account_id: another_account.id})
      |> Repo.update()

    assert unchanged.account_id == account.id

    assert {:ok, updated} =
      user
      |> change(account_id: another_account.id)
      |> User.changeset(%{})
      |> Repo.update()

    assert updated.id == user.id
    assert Repo.preload(updated, :account).account.id == another_account.id
  end

  test "does not delete a shared account when a user is deleted", %{account: account} do
    alice = insert_user!(account, "alice")
    bob = insert_user!(account, "bob")
    Repo.delete!(alice)

    assert Repo.get!(Account, account.id).type == :member
    assert Repo.preload(bob, :account).account.id == account.id
  end

  test "does not delete an account referenced by users", %{account: account} do
    insert_user!(account, "alice")

    assert {:error, changeset} = account |> Account.changeset(%{}) |> Repo.delete()
    assert "are still associated with this entry" in errors_on(changeset).users
    assert Repo.get!(Account, account.id).type == :member
  end

  test "persists the email and a trusted verification key", %{account: account} do
    key = String.duplicate("user-key", 16)

    changeset =
      %User{
        account_id: account.id,
        hashed_password: @hashed_password,
        verification_key: key
      }
      |> User.changeset(%{login: "alice", email: " Alice+notes@Example.COM "})

    assert {:ok, user} = Repo.insert(changeset)
    reloaded = Repo.get!(User, user.id)

    assert reloaded.email == "alice+notes@example.com"
    assert reloaded.verification_key == key

    assert %{rows: [[stored]]} =
      Repo.query!("SELECT verification_key FROM users WHERE id = $1", [user.id])

    refute stored == key
    assert {:ok, ^key} = EncryptedString.load(stored)
    refute inspect(reloaded) =~ key
    refute inspect(changeset) =~ key
  end

  test "stores a 344-byte verification key as exactly 512 encrypted characters", %{
    account: account
  } do
    key = String.duplicate("k", 344)

    assert {:ok, user} =
      %User{account_id: account.id, hashed_password: @hashed_password, verification_key: key}
      |> User.changeset(%{login: "alice"})
      |> Repo.insert()

    assert %{rows: [[stored]]} =
      Repo.query!("SELECT verification_key FROM users WHERE id = $1", [user.id])

    assert byte_size(stored) == 512
    assert Repo.get!(User, user.id).verification_key == key
  end

  test "validates verification key length in bytes before encryption", %{account: account} do
    for key <- [String.duplicate("k", 345), String.duplicate("🔐", 87)] do
      changeset =
        %User{account_id: account.id, hashed_password: @hashed_password, verification_key: key}
        |> User.changeset(%{login: "alice"})

      assert "should be at most 344 byte(s)" in errors_on(changeset).verification_key
      assert {:error, _changeset} = Repo.insert(changeset)
    end
  end

  test "encrypts a replacement verification key", %{account: account} do
    user = insert_user!(account, "alice")
    key = String.duplicate("k", 256)

    assert {:ok, updated} =
      user
      |> change(verification_key: key)
      |> User.changeset(%{})
      |> Repo.update()

    assert %{rows: [[stored]]} =
      Repo.query!("SELECT verification_key FROM users WHERE id = $1", [updated.id])

    refute stored == key
    assert Repo.get!(User, updated.id).verification_key == key
  end

  test "rejects an oversized replacement verification key", %{account: account} do
    user = insert_user!(account, "alice")

    changeset =
      user
      |> change(verification_key: String.duplicate("k", 345))
      |> User.changeset(%{})

    assert "should be at most 344 byte(s)" in errors_on(changeset).verification_key
    assert {:error, _changeset} = Repo.update(changeset)
    assert Repo.get!(User, user.id).verification_key == nil
  end

  test "accepts basic email addresses", %{account: account} do
    for email <- ["alice@example.com", "alice+notes@sub.example.com", "alice.smith@example.org"] do
      changeset =
        User.changeset(%User{account_id: account.id, hashed_password: @hashed_password}, %{
          login: "alice",
          email: email
        })

      assert changeset.valid?
    end
  end

  test "rejects malformed email addresses", %{account: account} do
    for email <- [
      "alice",
      "@example.com",
      "alice@",
      "alice@@example.com",
      "alice smith@example.com",
      "alice@exam ple.com",
      "alice\nsmith@example.com",
      "alice@example.com;bob@example.com",
      "alice,smith@example.com"
    ] do
      changeset =
        User.changeset(%User{account_id: account.id, hashed_password: @hashed_password}, %{
          login: "alice",
          email: email
        })

      assert "must have the @ sign and no spaces" in errors_on(changeset).email
    end
  end

  test "rejects oversized email addresses", %{account: account} do
    changeset =
      User.changeset(%User{account_id: account.id, hashed_password: @hashed_password}, %{
        login: "alice",
        email: String.duplicate("a", 250) <> "@example.com"
      })

    assert "should be at most 254 character(s)" in errors_on(changeset).email
  end

  test "enforces unique emails regardless of case", %{account: account} do
    %User{account_id: account.id, hashed_password: @hashed_password}
    |> User.changeset(%{login: "alice", email: "alice@example.com"})
    |> Repo.insert!()

    assert {:error, changeset} =
      %User{account_id: account.id, hashed_password: @hashed_password}
      |> User.changeset(%{login: "bob", email: " ALICE@EXAMPLE.COM "})
      |> Repo.insert()

    assert "has already been taken" in errors_on(changeset).email
  end

  test "enforces case-insensitive uniqueness even without email normalization", %{
    account: account
  } do
    %User{account_id: account.id, hashed_password: @hashed_password}
    |> User.changeset(%{login: "alice", email: "alice@example.com"})
    |> Repo.insert!()

    assert {:error, changeset} =
      %User{account_id: account.id, hashed_password: @hashed_password, email: "ALICE@EXAMPLE.COM"}
      |> User.changeset(%{login: "bob"})
      |> Repo.insert()

    assert "has already been taken" in errors_on(changeset).email
  end

  defp insert_user!(account, login) do
    %User{account_id: account.id, hashed_password: @hashed_password}
    |> User.changeset(%{login: login})
    |> Repo.insert!()
  end
end
